#!/usr/bin/env node
// Combine every catalog.cex below a folder into one catalog.cex at its top, with each
// image path made relative to the top folder (A/catalog.cex's "A1.jpg" → "A/A1.jpg").
//
//   npm run merge-catalogs -- <root> [--out FILE] [--dry-run] [--force]
//
// Catalogs are read folder by folder (A/, A/C/, A-Z/, B/ …), rows in their own order. Columns are
// matched by name; the output has path|caption|credits|license|tags, then year|place|urn
// and any other columns only if some catalog uses them. Skips dotfolders, _thumbs/ and the
// output file itself. A path already seen is kept once (first wins, with a warning); paths
// that point outside their catalog's folder ("../x.jpg") are skipped with a warning.
//
// The output starts with a "// Generated by …" comment. Rerunning replaces such a file, but a
// catalog.cex at the top that wasn't generated (hand-made) is left alone unless --force.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve, sep } from "node:path";
import { posix } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { THUMBS_DIR } from "./lib/index-lib.mjs";

export const CATALOG_NAME = "catalog.cex";
export const BASE_COLUMNS = ["path", "caption", "credits", "license", "tags"];
export const OPTIONAL_COLUMNS = ["year", "place", "urn"];
export const MARKER = "// Generated by utils/merge-catalogs.mjs";

/** Root-relative forward-slash paths of every catalog.cex below root (sorted), minus exclude. */
export async function findCatalogs(root, exclude = []) {
  const skip = new Set(exclude);
  const out = [];
  async function walk(dir) {
    for (const ent of await readdir(dir, { withFileTypes: true })) {
      if (ent.name.startsWith(".")) continue;
      if (dir === root && ent.name === THUMBS_DIR) continue;
      const full = join(dir, ent.name);
      if (ent.isDirectory()) await walk(full);
      else if (ent.isFile() && ent.name === CATALOG_NAME) {
        const rel = relative(root, full).split(sep).join("/");
        if (!skip.has(rel)) out.push(rel);
      }
    }
  }
  await walk(root);
  return out.sort(byFolder);
}

/** Order catalogs by folder, one name at a time, so a folder's subfolders follow it
 *  directly: catalog.cex, A/…, A/C/…, A-Z/…, B/… */
export function byFolder(a, b) {
  const sa = posix.dirname(a).split("/").filter((s) => s !== ".");
  const sb = posix.dirname(b).split("/").filter((s) => s !== ".");
  for (let i = 0; i < Math.min(sa.length, sb.length); i++) {
    if (sa[i] !== sb[i]) return sa[i] < sb[i] ? -1 : 1;
  }
  return sa.length - sb.length;
}

/** Parse catalog text (same rules as the apps: header line, `//` and `#!` lines skipped). */
export function parseCatalogText(text) {
  const rows = [];
  const errors = [];
  let headers = null;
  text.replace(/^﻿/, "").split(/\r?\n/).forEach((raw, i) => {
    const line = raw.trim();
    if (!line || line.startsWith("//") || line.startsWith("#!")) return;
    const cells = raw.split("|").map((c) => c.trim());
    if (!headers) { headers = cells.map((h) => h.toLowerCase().replace(/\s+/g, "_")); return; }
    if (cells.length !== headers.length) errors.push(`line ${i + 1}: expected ${headers.length} fields, found ${cells.length}`);
    const row = {};
    headers.forEach((h, j) => (row[h] = cells[j] ?? ""));
    rows.push(row);
  });
  return { headers: headers ?? [], rows, errors };
}

/** "dir" + catalog path → root-relative path, or null if it leaves the catalog's folder. */
export function joinPath(dir, p) {
  const clean = p.trim().replace(/\\/g, "/").replace(/^\.?\/+/, "");
  if (!clean) return null;
  const joined = posix.normalize(dir && dir !== "." ? `${dir}/${clean}` : clean);
  const within = !dir || dir === "." ? !joined.startsWith("../") && joined !== ".." : joined.startsWith(`${dir}/`);
  return within ? joined : null;
}

/**
 * Merge catalogs. `catalogs` is [{ file: root-relative path, text }].
 * Returns { headers, rows, warnings }.
 */
export function mergeCatalogs(catalogs) {
  const rows = [];
  const warnings = [];
  const seen = new Map(); // path → catalog it came from
  const extra = [];
  const used = new Set();
  for (const { file, text } of catalogs) {
    const dir = posix.dirname(file);
    const t = parseCatalogText(text);
    for (const e of t.errors) warnings.push(`${file} ${e}`);
    if (!t.headers.includes("path")) { warnings.push(`${file}: no "path" column, skipped`); continue; }
    for (const h of t.headers) if (!BASE_COLUMNS.includes(h) && !OPTIONAL_COLUMNS.includes(h) && !extra.includes(h)) extra.push(h);
    for (const r of t.rows) {
      if (!r.path?.trim()) { warnings.push(`${file}: row with empty path skipped`); continue; }
      const path = joinPath(dir, r.path);
      if (!path) { warnings.push(`${file}: "${r.path}" is outside ${dir}/, skipped`); continue; }
      if (seen.has(path)) { warnings.push(`${file}: ${path} already cataloged in ${seen.get(path)}, skipped`); continue; }
      seen.set(path, file);
      for (const [k, v] of Object.entries(r)) if (v) used.add(k);
      rows.push({ ...r, path });
    }
  }
  const headers = [...BASE_COLUMNS, ...OPTIONAL_COLUMNS.filter((c) => used.has(c)), ...extra.filter((c) => used.has(c))];
  return { headers, rows, warnings };
}

/** Output text: marker comment, header, rows. */
export function catalogText(headers, rows, sources) {
  return [
    `${MARKER} from ${sources.length} catalog(s); rerun to update, don't edit.`,
    headers.join("|"),
    ...rows.map((r) => headers.map((h) => r[h] ?? "").join("|")),
  ].join("\n") + "\n";
}

/** Scan root and write the merged catalog. Returns { sources, rows, warnings, out, written }. */
export async function mergeCatalogTree(root, { out = join(root, CATALOG_NAME), dryRun = false, force = false } = {}) {
  root = resolve(root);
  out = resolve(out);
  const outRel = relative(root, out).split(sep).join("/");
  const sources = await findCatalogs(root, [outRel]);
  const catalogs = [];
  for (const file of sources) catalogs.push({ file, text: await readFile(join(root, file), "utf8") });
  const { headers, rows, warnings } = mergeCatalogs(catalogs);
  const result = { sources, rows: rows.length, warnings, out, written: false };
  if (dryRun) return result;
  let existing = null;
  try { existing = await readFile(out, "utf8"); } catch (e) { if (e.code !== "ENOENT") throw e; }
  if (existing !== null && !existing.replace(/^﻿/, "").startsWith(MARKER) && !force) {
    throw new Error(`${out} exists and wasn't made by merge-catalogs; use --force to replace it or --out to write elsewhere.`);
  }
  await writeFile(out, catalogText(headers, rows, sources));
  result.written = true;
  return result;
}

async function main() {
  const { values, positionals } = parseArgs({ allowPositionals: true, options: {
    out: { type: "string" },
    "dry-run": { type: "boolean", default: false },
    force: { type: "boolean", default: false },
  } });
  if (positionals.length !== 1) throw new Error("Usage: npm run merge-catalogs -- <root> [--out FILE] [--dry-run] [--force]");
  const root = positionals[0];
  const r = await mergeCatalogTree(root, { out: values.out, dryRun: values["dry-run"], force: values.force });
  for (const s of r.sources) console.log(`  ${s}`);
  for (const w of r.warnings) console.log(`WARNING: ${w}`);
  console.log(`${r.sources.length} catalog(s), ${r.rows} image(s) → ${r.out}` + (r.written ? "" : " (dry run, nothing written)"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => { console.error(e.message); process.exit(1); });
}
